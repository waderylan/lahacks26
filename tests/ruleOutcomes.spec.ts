import { expect, test, type Page } from '@playwright/test';
import { startRuleApp } from './fixtures/ruleApp';

let app: Awaited<ReturnType<typeof startRuleApp>>;
test.beforeEach(async () => { app = await startRuleApp(); });
test.afterEach(async () => { await app?.close(); });
const step = (page: Page, name: string) => page.getByRole('navigation', { name: 'Rule setup steps' }).getByRole('button', { name, exact: true }).click();

test('outcome actions are explained, previewed, saved, and executed in their own branches', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${app.url}/?workspace=rules&editRule=1`);
  await page.getByRole('button', { name: 'New rule', exact: true }).click();
  await page.getByLabel('Condition 1', { exact: true }).fill('This charge is a duplicate without supporting documentation.');
  await expect(page.getByLabel('Evaluation progress')).toContainText('8/8 evaluated · Complete');
  await step(page, 'Choose actions');
  const match = page.getByRole('group', { name: 'When there is a match', exact: true });
  const uncertain = page.getByRole('group', { name: 'When there is not enough information', exact: true });
  const nonmatch = page.getByRole('group', { name: 'When there is no match', exact: true });
  await expect(uncertain).toContainText('Jev cannot decide from the available records.');
  await match.getByRole('button', { name: 'Add action', exact: true }).click();
  await match.getByLabel('Action value').fill('Check charge');
  await uncertain.getByRole('button', { name: 'Add action for uncertain results', exact: true }).click();
  await expect(uncertain.getByLabel('Action type').locator('option[value=pass]')).toHaveCount(0);
  await uncertain.getByLabel('Action type').selectOption('message');
  await uncertain.getByLabel('Message request').fill('Ask for the missing receipt.');
  await nonmatch.getByRole('button', { name: 'Add action for nonmatches', exact: true }).click();
  await nonmatch.getByLabel('Action type').selectOption('tag');
  await nonmatch.getByLabel('Action value').fill('No issue');
  await page.locator('.rule-wizard').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: 'artifacts/outcome-actions-desktop.png', fullPage: true });
  await step(page, 'Review results');
  await expect(page.locator('.wizard-table tbody tr')).toHaveCount(8);
  await expect(page.locator('tr[data-id="company-101:bill-1"]')).toContainText('Draft message');
  await expect(page.locator('tr[data-id="company-101:bill-2"]')).toContainText('Check charge');
  await expect(page.locator('tr[data-id="company-101:bill-3"]')).toContainText('No issue');
  await page.getByLabel('Rule name').fill('Review charge documentation');
  await page.getByRole('button', { name: 'Save rule', exact: true }).click();
  await expect(page.getByRole('button', { name: /Run/ })).toContainText('8 transactions');
  await page.getByRole('button', { name: /Run/ }).click();
  const saved = async () => (await (await page.request.get(`${app.url}/api/companies/company-101/rules`)).json()).store;
  await expect.poll(async () => (await saved()).messages[0]?.generation).toBe('ready');
  const state = await saved();
  expect(state.transactions['company-101:bill-2'].flags).toEqual(['Check charge']);
  expect(state.transactions['company-101:bill-1']).toBeUndefined();
  expect(state.transactions['company-101:bill-3'].tags).toEqual(['No issue']);
  expect(state.messages[0].outcome).toBe('uncertain');
  expect(state.messages[0].status).toBe('pending');
  const count = state.history.length;
  await page.getByRole('button', { name: /Run/ }).click();
  await expect.poll(async () => (await saved()).history.length).toBe(count);
  await page.reload(); await page.getByRole('button', { name: 'Edit rule', exact: true }).click(); await step(page, 'Choose actions');
  await expect(uncertain.getByLabel('Message request')).toHaveValue('Ask for the missing receipt.');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'What should happen for each result?' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/outcome-actions-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('supporting details clear a tracked flag and complete its task after an automatic recheck', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${app.url}/?workspace=rules&editRule=1`);
  await page.getByRole('button', { name: 'New rule', exact: true }).click();
  await page.getByLabel('Condition 1', { exact: true }).fill('This charge lacks supporting documentation.');
  await expect(page.getByLabel('Evaluation progress')).toContainText('8/8 evaluated · Complete');
  await step(page, 'Choose actions');
  const uncertain = page.getByRole('group', { name: 'When there is not enough information', exact: true });
  await uncertain.getByRole('button', { name: 'Add action for uncertain results', exact: true }).click();
  await uncertain.getByLabel('Action value').fill('Needs receipt');
  await uncertain.getByRole('button', { name: 'Add action for uncertain results', exact: true }).click();
  await uncertain.getByLabel('Action type').last().selectOption('task');
  await uncertain.getByLabel('Task title').fill('Verify this receipt');
  await uncertain.getByLabel('Task owner').selectOption('emp-ap');
  await uncertain.getByLabel('Task due in days').fill('2');
  await expect(page.getByLabel('Clear resolved issues')).not.toBeChecked();
  await page.getByLabel('Clear resolved issues').check();
  await expect(page.getByLabel('After an issue is cleared')).toContainText('A match or an uncertain result keeps the issue open.');
  await page.locator('.wizard-resolution').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/automatic-resolution-setting.png', fullPage: true });
  await step(page, 'Review results');
  await page.getByLabel('Rule name').fill('Request missing receipt');
  await page.getByRole('button', { name: 'Save rule', exact: true }).click();
  await page.getByLabel('Keep checking', { exact: true }).click();
  await expect(page.getByLabel('Keep checking', { exact: true })).toBeChecked();
  await expect(page.getByRole('button', { name: /Run/ })).toContainText('1 transaction');
  await page.getByRole('button', { name: /Run/ }).click();
  await expect(page.getByLabel('Rule follow-up')).toContainText('1 open · 0 resolved');
  await page.locator('tr[data-id="company-101:bill-1"] .wizard-vendor').click();
  const drawer = page.getByLabel('Transaction detail');
  await expect(drawer.getByLabel('Rule follow-up')).toContainText('Open');
  await drawer.getByLabel('Supporting details title').fill('Receipt verification');
  await drawer.getByLabel('Supporting details text').fill('The original receipt confirms this was a single maintenance charge.');
  await drawer.getByRole('button', { name: 'Save supporting details', exact: true }).click();
  await expect(drawer.getByRole('status')).toContainText('Details saved.');
  await expect(drawer.getByLabel('Rule follow-up')).toContainText('Resolved');
  await expect(drawer).toContainText('The original receipt confirms');
  await page.getByLabel('Close detail', { exact: true }).click();
  await expect(page.getByLabel('Rule follow-up')).toContainText('0 open · 1 resolved');
  await page.getByLabel('Rule follow-up').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/resolved-rule-issue.png', fullPage: true });
  const state = await (await page.request.get(`${app.url}/api/companies/company-101/rules`)).json();
  const issue = state.issues.find((issue: any) => issue.ruleName === 'Request missing receipt');
  const workspace = await (await page.request.get(`${app.url}/api/companies/company-101/workspace`)).json();
  expect(workspace.tasks.find((task: any) => issue.taskIds.includes(task.id)).status).toBe('done');
  expect(state.rows.find((row: any) => row.id === 'company-101:bill-1').dashboard.flags).not.toContain('Needs receipt');
  await page.getByRole('button', { name: 'View activity', exact: true }).click();
  await expect(page.locator('.activity-list li').filter({ hasText: 'Issue resolved' })).toContainText('Cleared 1 flag and completed 1 task.');
  await page.reload();
  await expect(page.locator('.activity-list li').filter({ hasText: 'Issue resolved' })).toHaveCount(1);
  await page.goto(`${app.url}/?workspace=rules`); await page.getByRole('button', { name: 'Edit rule', exact: true }).click(); await step(page, 'Choose actions');
  await expect(page.getByLabel('Clear resolved issues')).toBeChecked();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.wizard-resolution').scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/automatic-resolution-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});

