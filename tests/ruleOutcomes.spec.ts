import { expect, test, type Page } from '@playwright/test';
import { startRuleApp } from './fixtures/ruleApp';

let app: Awaited<ReturnType<typeof startRuleApp>>;
test.beforeAll(async () => { app = await startRuleApp(); });
test.afterAll(async () => { await app?.close(); });
const step = (page: Page, name: string) => page.getByRole('navigation', { name: 'Rule setup steps' }).getByRole('button', { name, exact: true }).click();

test('outcome actions are explained, previewed, saved, and executed in their own branches', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${app.url}/?workspace=rules`);
  await page.getByRole('button', { name: 'New rule', exact: true }).click();
  await page.getByLabel('Condition 1', { exact: true }).fill('This charge is a duplicate without supporting documentation.');
  await expect(page.getByLabel('Evaluation progress')).toContainText('8/8 evaluated · Complete');
  await step(page, 'Choose actions');
  const match = page.getByRole('group', { name: 'When there is a match', exact: true });
  const uncertain = page.getByRole('group', { name: 'When there is not enough information', exact: true });
  const nonmatch = page.getByRole('group', { name: 'When there is no match', exact: true });
  await expect(uncertain).toContainText('Jev cannot decide from the available records.');
  await match.getByRole('button', { name: 'Add action', exact: true }).click();
  await match.getByLabel('Action value').fill('Check charge');
  await uncertain.getByRole('button', { name: 'Add action for uncertain results', exact: true }).click();
  await expect(uncertain.getByLabel('Action type').locator('option[value=pass]')).toHaveCount(0);
  await uncertain.getByLabel('Action type').selectOption('message');
  await uncertain.getByLabel('Message request').fill('Ask for the missing receipt.');
  await nonmatch.getByRole('button', { name: 'Add action for nonmatches', exact: true }).click();
  await nonmatch.getByLabel('Action type').selectOption('tag');
  await nonmatch.getByLabel('Action value').fill('No issue');
  await page.locator('.rule-wizard').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: 'artifacts/outcome-actions-desktop.png', fullPage: true });
  await step(page, 'Review matches');
  await expect(page.locator('.wizard-table tbody tr')).toHaveCount(8);
  await expect(page.locator('tr[data-id="company-018:bill-1"]')).toContainText('Draft message');
  await expect(page.locator('tr[data-id="company-018:bill-2"]')).toContainText('Check charge');
  await expect(page.locator('tr[data-id="company-018:bill-3"]')).toContainText('No issue');
  await page.getByLabel('Rule name').fill('Review charge documentation');
  await page.getByRole('button', { name: 'Save rule', exact: true }).click();
  await expect(page.getByRole('button', { name: /Run once/ })).toContainText('8 transactions');
  await page.getByRole('button', { name: /Run once/ }).click();
  const saved = async () => (await (await page.request.get(`${app.url}/api/companies/company-018/rules`)).json()).store;
  await expect.poll(async () => (await saved()).messages[0]?.generation).toBe('ready');
  const state = await saved();
  expect(state.transactions['company-018:bill-2'].flags).toEqual(['Check charge']);
  expect(state.transactions['company-018:bill-1']).toBeUndefined();
  expect(state.transactions['company-018:bill-3'].tags).toEqual(['No issue']);
  expect(state.messages[0].outcome).toBe('uncertain');
  expect(state.messages[0].status).toBe('pending');
  const count = state.history.length;
  await page.getByRole('button', { name: /Run once/ }).click();
  await expect.poll(async () => (await saved()).history.length).toBe(count);
  await page.reload(); await step(page, 'Choose actions');
  await expect(uncertain.getByLabel('Message request')).toHaveValue('Ask for the missing receipt.');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'What should happen for each result?' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/outcome-actions-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});
